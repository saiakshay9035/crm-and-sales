"""
Anti-Hallucination Gate for Autonomous AI SDR Platform.
Enforces strict provenance, fact-checking, and evidence-grounding for every
personalized claim, pain point, and buying trigger generated by any agent.

Every personalized statement MUST have:
1. Source URL (verifiable public web, GitHub, news, job board)
2. Evidence extracted (verbatim or high-fidelity quoted text)
3. Date discovered (ISO timestamp)
4. Confidence score (0.0 - 1.0, >= MIN_CONFIDENCE threshold)

No agent is permitted to invent or assume a company's pain point.
"""

from dataclasses import dataclass, asdict, field
from datetime import datetime, timezone
import re
import urllib.parse
from typing import Optional, Union, List, Dict, Tuple
import logging

logger = logging.getLogger("evidence_gate")

MIN_CONFIDENCE_THRESHOLD = 0.65
MIN_EVIDENCE_LENGTH = 10

# Banned hallucination markers commonly invented by untrained sales LLMs
FORBIDDEN_UNVERIFIED_PAIN_CLUSTERS = [
    {"terms": ["salary overhead", "expensive developers", "high salary"], "label": "Developer Salary Overhead"},
    {"terms": ["freelancer drag", "managing freelancers", "unreliable freelancers"], "label": "Freelancer Management Issues"},
    {"terms": ["legacy codebase", "technical debt crisis", "spaghetti code"], "label": "Legacy Code Debt"},
    {"terms": ["missed deadlines", "falling behind competitors", "failing to ship"], "label": "Delivery Failure"},
    {"terms": ["security vulnerability", "leaking data", "compromised systems"], "label": "Security Vulnerability"},
    {"terms": ["burnout", "team exhaustion", "quitting engineers"], "label": "Team Burnout"}
]


@dataclass
class EvidenceItem:
    source_url: str
    evidence_extracted: str
    date_discovered: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    confidence_score: float = 1.0
    signal_type: str = "BUYING_TRIGGER"  # PAIN_POINT, BUYING_TRIGGER, HIRING, FUNDING, TECH_STACK
    statement: str = ""
    lead_id: Optional[str] = None
    id: Optional[int] = None

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "EvidenceItem":
        # Safe constructor handling extra keys or missing fields
        valid_keys = {
            "source_url", "evidence_extracted", "date_discovered",
            "confidence_score", "signal_type", "statement", "lead_id", "id"
        }
        filtered = {k: v for k, v in data.items() if k in valid_keys}
        return cls(**filtered)


class AntiHallucinationGate:
    """
    Guards outbound sales copy and company intelligence from LLM hallucinations.
    Ensures zero fabricated pain points or buying triggers.
    """

    def __init__(self, min_confidence: float = MIN_CONFIDENCE_THRESHOLD):
        self.min_confidence = min_confidence

    def validate_evidence(self, item: Union[EvidenceItem, Dict]) -> Tuple[bool, str]:
        """
        Validates the 4 mandatory provenance criteria:
        1. Source URL
        2. Evidence extracted
        3. Date discovered
        4. Confidence score
        """
        if isinstance(item, dict):
            source_url = (item.get("source_url") or "").strip()
            evidence_extracted = (item.get("evidence_extracted") or "").strip()
            date_discovered = (item.get("date_discovered") or "").strip()
            try:
                confidence_score = float(item.get("confidence_score", 0.0))
            except (ValueError, TypeError):
                confidence_score = 0.0
            signal_type = (item.get("signal_type") or "").strip()
        else:
            source_url = item.source_url.strip() if item.source_url else ""
            evidence_extracted = item.evidence_extracted.strip() if item.evidence_extracted else ""
            date_discovered = item.date_discovered.strip() if item.date_discovered else ""
            confidence_score = float(item.confidence_score)
            signal_type = item.signal_type.strip() if item.signal_type else ""

        # 1. Validate Source URL
        if not source_url:
            return False, "REJECTED: Missing required 'source_url'."
        
        parsed_url = urllib.parse.urlparse(source_url)
        if parsed_url.scheme not in ("http", "https"):
            return False, f"REJECTED: 'source_url' must have http or https scheme: {source_url}"
        if not parsed_url.netloc or "." not in parsed_url.netloc:
            return False, f"REJECTED: 'source_url' has invalid host/domain: {source_url}"

        # 2. Validate Evidence Extracted
        if not evidence_extracted:
            return False, "REJECTED: Missing required 'evidence_extracted' snippet."
        if len(evidence_extracted) < MIN_EVIDENCE_LENGTH:
            return False, f"REJECTED: 'evidence_extracted' too short ({len(evidence_extracted)} chars, minimum {MIN_EVIDENCE_LENGTH})."
        
        placeholder_regex = re.compile(r"^(n/a|none|unknown|placeholder|fake|test|dummy|undefined)$", re.IGNORECASE)
        if placeholder_regex.match(evidence_extracted):
            return False, f"REJECTED: 'evidence_extracted' contains placeholder text: '{evidence_extracted}'."

        # 3. Validate Date Discovered
        if not date_discovered:
            return False, "REJECTED: Missing required 'date_discovered' timestamp."
        try:
            # Check ISO format compatibility
            clean_date = date_discovered.replace("Z", "+00:00")
            datetime.fromisoformat(clean_date)
        except Exception:
            return False, f"REJECTED: 'date_discovered' is not a valid ISO 8601 timestamp: '{date_discovered}'."

        # 4. Validate Confidence Score
        if confidence_score < self.min_confidence:
            return False, f"REJECTED: 'confidence_score' {confidence_score:.2f} is below minimum threshold {self.min_confidence:.2f}."
        if confidence_score > 1.0:
            return False, f"REJECTED: 'confidence_score' {confidence_score:.2f} cannot exceed 1.0."

        return True, "VALID"

    def filter_verified_evidence(self, raw_items: List[Union[EvidenceItem, Dict]]) -> List[EvidenceItem]:
        """Filters a list of candidate evidence items, keeping only verified records."""
        verified = []
        for raw in raw_items:
            is_valid, reason = self.validate_evidence(raw)
            if is_valid:
                item = raw if isinstance(raw, EvidenceItem) else EvidenceItem.from_dict(raw)
                verified.append(item)
            else:
                logger.warning(f"[Anti-Hallucination Gate] {reason}")
        return verified

    def verify_statement(
        self,
        statement: str,
        evidence_items: List[Union[EvidenceItem, Dict]]
    ) -> Tuple[bool, str]:
        """
        Verifies that a specific personalized statement or hook is grounded in
        one of the provided evidence records. Specifically blocks hallucinated pain points.
        """
        if not statement or not statement.strip():
            return False, "Statement is empty."

        verified_evidence = self.filter_verified_evidence(evidence_items)
        if not verified_evidence:
            return False, "REJECTED: No verified evidence provided to ground this statement."

        # Combine all verified evidence snippets into one search corpus
        corpus = " ".join([item.evidence_extracted.lower() for item in verified_evidence])

        statement_lower = statement.lower()

        # Check for unverified pain assertions
        for cluster in FORBIDDEN_UNVERIFIED_PAIN_CLUSTERS:
            for term in cluster["terms"]:
                if term in statement_lower:
                    # Check if the term or cluster concept is explicitly present in the verified evidence corpus
                    if not any(t in corpus for t in cluster["terms"]):
                        return False, (
                            f"HALLUCINATION REJECTED: Statement asserts pain point '{cluster['label']}' "
                            f"('{term}'), but no verified evidence mentions it."
                        )

        # Ensure at least some token overlap between statement and evidence corpus
        statement_tokens = set(re.findall(r"\b[a-zA-Z]{4,}\b", statement_lower))
        corpus_tokens = set(re.findall(r"\b[a-zA-Z]{4,}\b", corpus))
        
        # Stop words to ignore in token overlap
        stop_words = {
            "this", "that", "with", "from", "your", "their", "have", "been", "were",
            "will", "would", "could", "should", "about", "there", "company", "team",
            "building", "growing", "making", "doing", "working"
        }
        meaningful_statement_tokens = statement_tokens - stop_words
        overlap = meaningful_statement_tokens.intersection(corpus_tokens)

        if not overlap:
            return False, "REJECTED: Statement shares zero substantive concepts with verified evidence."

        return True, "GROUNDED"

    def enforce_pitch_grounding(
        self,
        pitch: str,
        evidence_items: List[Union[EvidenceItem, Dict]]
    ) -> Tuple[bool, List[str]]:
        """
        Scans a complete cold email / outreach pitch for ungrounded claims or hallucinated pain points.
        Returns (is_clean, list_of_violations).
        """
        violations = []
        pitch_lower = pitch.lower()
        verified_evidence = self.filter_verified_evidence(evidence_items)
        corpus = " ".join([item.evidence_extracted.lower() for item in verified_evidence])

        for cluster in FORBIDDEN_UNVERIFIED_PAIN_CLUSTERS:
            for term in cluster["terms"]:
                if term in pitch_lower:
                    if not any(t in corpus for t in cluster["terms"]):
                        violations.append(
                            f"Hallucinated pain point '{cluster['label']}' ('{term}') found in pitch without supporting evidence."
                        )
                        break

        is_clean = len(violations) == 0
        return is_clean, violations

    def sanitize_pitch(
        self,
        pitch: str,
        company_name: str,
        evidence_items: List[Union[EvidenceItem, Dict]]
    ) -> str:
        """
        If a pitch contains unverified or hallucinated pain assertions,
        sanitizes them into courteous, non-presumptive inquiry statements.
        """
        clean_pitch = pitch
        verified_evidence = self.filter_verified_evidence(evidence_items)
        corpus = " ".join([item.evidence_extracted.lower() for item in verified_evidence])

        for cluster in FORBIDDEN_UNVERIFIED_PAIN_CLUSTERS:
            for term in cluster["terms"]:
                if term in clean_pitch.lower() and not any(t in corpus for t in cluster["terms"]):
                    # Replace aggressive assumed pain line with an open inquiry
                    pattern = re.compile(rf"[^.\n]*?{re.escape(term)}[^.\n]*?\.", re.IGNORECASE)
                    replacement = f"Curious how your team is currently prioritizing product delivery and scaling."
                    clean_pitch = pattern.sub(replacement, clean_pitch)

        return clean_pitch

    @staticmethod
    def format_citation(item: EvidenceItem) -> str:
        """Formats an evidence record into a verifiable provenance citation."""
        date_str = item.date_discovered.split("T")[0] if "T" in item.date_discovered else item.date_discovered[:10]
        conf_pct = int(item.confidence_score * 100)
        return f"[Source: {item.source_url} | Discovered: {date_str} | Confidence: {conf_pct}%] \"{item.evidence_extracted}\""


# Global default instance
default_gate = AntiHallucinationGate()
